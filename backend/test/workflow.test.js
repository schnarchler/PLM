test('Auftrag: Status läuft beim Fertigen mit, Material wird abgebucht', async () => {
  const proj = await api('/api/projects', 'POST', { name: 'Fertigung' });
  const teil = await api(`/api/projects/${proj.id}/items`, 'POST', { name: 'Deckel', item_type: 'prt' });
  await api(`/api/revisions/${await firstRev(teil.id)}/print-settings`, 'PUT', { material: 'PETG', filament_weight_total: 184 });
  const mat = await api('/api/raw-materials', 'POST', { name: 'PETG schwarz', unit: 'Stk', weight_g: 1000, stock_qty: 0 });
  await api(`/api/raw-materials/${mat.id}/adjust`, 'POST', { qty: 3, type: 'in', lot_number: 'LOT-A' });

  const order = await api('/api/orders', 'POST', { title: 'Serie Deckel' });
  assert.strictEqual(order.status, 'DRAFT');
  await api(`/api/orders/${order.id}/items`, 'POST', { description: 'Deckel', quantity: 10, unit: 'Stk', unit_price: 12.5, item_id: teil.id });
  const los = await api(`/api/orders/${order.id}/to-delivery`, 'POST', {});
  assert.strictEqual((await api(`/api/orders/${order.id}`)).status, 'CONFIRMED', 'Fertigen bestätigt den Auftrag');
  assert.strictEqual((await api(`/api/orders/${order.id}`)).deliveries.length, 1, 'Los hängt am Auftrag');

  const di = (await api(`/api/deliveries/${los.id}`)).items[0];
  await api(`/api/delivery-items/${di.id}`, 'PUT',
    { description: 'Deckel', quantity: 10, unit: 'Stk', unit_price: 12.5, item_id: teil.id, raw_material_id: mat.id });
  const usage = await api(`/api/deliveries/${los.id}/material-usage`);
  const row = usage.rows[0];
  assert.strictEqual(row.grams_per_piece, 184);
  assert.strictEqual(row.total_grams, 1840);
  assert.ok(Math.abs(row.qty_to_deduct - 1.84) < 0.001, 'Gramm werden in Spulen umgerechnet');

  await api(`/api/deliveries/${los.id}/consume-material`, 'POST',
    { consumptions: [{ raw_material_id: mat.id, qty: row.qty_to_deduct, lot_number: 'LOT-A' }] });
  const after = (await api('/api/raw-materials')).find(m => m.id === mat.id);
  assert.ok(Math.abs(after.stock_qty - (3 - 1.84)) < 0.001, `Bestand ${after.stock_qty}`);
  const again = await apiFails(`/api/deliveries/${los.id}/consume-material`, 'POST', { consumptions: [] });
  assert.strictEqual(again.status, 400, 'kein zweites Abbuchen');

  await api(`/api/deliveries/${los.id}/status`, 'PUT', { status: 'DELIVERED' });
  assert.strictEqual((await api(`/api/orders/${order.id}`)).status, 'DELIVERED', 'alle Lose fertig → Auftrag geliefert');
});

