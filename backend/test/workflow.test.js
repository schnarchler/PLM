test('Stückliste: Revision folgt automatisch, bis sie fixiert wird', async () => {
  const proj = await api('/api/projects', 'POST', { name: 'Fixierung' });
  const mk = n => api(`/api/projects/${proj.id}/items`, 'POST', { name: n, item_type: n.startsWith('F') ? 'asm' : 'prt' });
  const teil = await mk('Teil'), f1 = await mk('Fahrzeug 1'), f3 = await mk('Fahrzeug 3');
  for (const f of [f1, f3]) {
    await api(`/api/revisions/${await firstRev(f.id)}/bom`, 'POST', { child_item_id: teil.id, quantity: 2, unit: 'Stk' });
  }
  let bom = (await api(`/api/items/${f1.id}`)).revisions[0].bom[0];
  assert.strictEqual(bom.child_rev_id, null, 'Standard ist automatisch');

  const r1 = (await api(`/api/items/${teil.id}`)).revisions[0];
  await api(`/api/bom/${bom.id}/revision`, 'PUT', { rev_id: r1.id });
  for (const st of [{ status: 'REV' }, { status: 'REL', released_by: 'Test' }, { status: 'ECO', eco_reason: 'Änderung' }]) {
    await api(`/api/revisions/${r1.id}/status`, 'PUT', st);
  }
  bom = (await api(`/api/items/${f1.id}`)).revisions[0].bom[0];
  const free = (await api(`/api/items/${f3.id}`)).revisions[0].bom[0];
  assert.strictEqual(bom.child_effective_rev.rev, '1', 'fixiert bleibt auf rev1');
  assert.strictEqual(bom.rev_outdated, true, 'und wird als veraltet gemeldet');
  assert.strictEqual(free.child_pinned_rev, null);
  assert.strictEqual(free.child_effective_rev.rev, '2', 'automatisch zieht auf rev2 mit');

  const wu = await api(`/api/items/${teil.id}/where-used`);
  assert.strictEqual(wu.filter(r => r.pinned_rev).length, 1, 'Verwendung zeigt den fixierten Stand');
  const g = await api(`/api/items/${teil.id}/graph?up=2&down=2`);
  assert.strictEqual(g.edges.filter(e => e.pinned_rev).length, 1, 'Mindmap-Kante trägt die Revision');

  const other = (await api(`/api/items/${f3.id}`)).revisions[0];
  const bad = await apiFails(`/api/bom/${free.id}/revision`, 'PUT', { rev_id: other.id });
  assert.strictEqual(bad.status, 400, 'fremde Revision wird abgewiesen');

  await api(`/api/bom/${bom.id}/revision`, 'PUT', { rev_id: null });
  assert.strictEqual((await api(`/api/items/${f1.id}`)).revisions[0].bom[0].child_pinned_rev, null);
});

