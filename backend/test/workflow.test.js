async function api(url, method = 'GET', body = null) {
  const opts = { method, headers: {} };
  if (body) { opts.headers['Content-Type'] = 'application/json'; opts.body = JSON.stringify(body); }
  const r = await fetch(BASE + url, opts);
  if (!r.ok) throw new Error(`${method} ${url} → HTTP ${r.status}: ${await r.text()}`);
  return r.json();
}
async function apiFails(url, method, body) {
  const opts = { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body ?? {}) };
  const r = await fetch(BASE + url, opts);
  return { status: r.status, text: await r.text() };
}

// Minimales 3MF: ZIP mit einer PrusaSlicer-Konfiguration.
function make3mf(file) {
  const cfg = Buffer.from([
    '; generated by PrusaSlicer 2.9.0', 'layer_height = 0.25', 'fill_density = 25%', 'fill_pattern = gyroid',
    'support_material = 1', 'nozzle_diameter = 0.6', 'temperature = 245',
    'bed_temperature = 85', 'filament_type = PETG', 'filament_colour = #FF8800',
    'printer_settings_id = Prusa MK4 0.6 nozzle', '',
  ].join('\n'), 'utf8');
  const name = Buffer.from('Metadata/Slic3r_PE.config', 'utf8');
  const crc = zlib.crc32 ? zlib.crc32(cfg) : require('node:zlib').crc32(cfg);
  const local = Buffer.alloc(30);
  local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0, 6);
  local.writeUInt16LE(0, 8); local.writeUInt32LE(crc, 14);
  local.writeUInt32LE(cfg.length, 18); local.writeUInt32LE(cfg.length, 22);
  local.writeUInt16LE(name.length, 26);
  const central = Buffer.alloc(46);
  central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6);
  central.writeUInt32LE(crc, 16); central.writeUInt32LE(cfg.length, 20);
  central.writeUInt32LE(cfg.length, 24); central.writeUInt16LE(name.length, 28);
  const centralOff = local.length + name.length + cfg.length;
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(1, 8); end.writeUInt16LE(1, 10);
  end.writeUInt32LE(central.length + name.length, 12); end.writeUInt32LE(centralOff, 16);
  fs.writeFileSync(file, Buffer.concat([local, name, cfg, central, name, end]));
}

async function upload3mf(revId, file) {
  const data = fs.readFileSync(file);
  const form = new FormData();
  form.append('file', new Blob([data]), 'teil.3mf');
  const r = await fetch(`${BASE}/api/revisions/${revId}/datasets`, { method: 'POST', body: form });
  assert.ok(r.ok, `Upload fehlgeschlagen: ${r.status}`);
  return r.json();
}

